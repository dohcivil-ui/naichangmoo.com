/**
 * รหัสอ้างอิงเป็นรหัสสั้นที่ตั้งใหม่ทุกครั้งที่ขอ ไม่ใช่ id ของแถวในฐานข้อมูล
 *
 * สองเหตุผล — id จริงเป็น uuid ยาว 36 ตัวอักษรต่อบรรทัด ซึ่งเป็น token ที่จ่ายไปโดยไม่ได้
 * ช่วยให้จับคู่แม่นขึ้นเลย และ id ของแถวไม่ควรเดินทางออกไปนอกเครื่องโดยไม่จำเป็น
 * ฝั่งเซิร์ฟเวอร์เก็บตารางแปลงกลับไว้เอง
 */
export type BoqMatchInput = {
  projectName: string;
  items: { ref: string; description: string; unit: string; quantity: string }[];
  lines: { ref: string; name: string; unit: string }[];
};

export function buildBoqMatchTask(input: BoqMatchInput, facts: string[]): string {
  return [
    `จับคู่รายการปริมาณของโครงการ ${input.projectName} เข้ากับบรรทัดในชุดราคาที่โครงการรับมาแล้ว`,
    "",
    "รายการปริมาณที่วิศวกรยืนยันแล้ว",
    ...input.items.map((item) => `- [${item.ref}] ${item.description} · หน่วย ${item.unit} · ปริมาณ ${item.quantity}`),
    "",
    "บรรทัดในชุดราคาของโครงการ",
    ...input.lines.map((line) => `- [${line.ref}] ${line.name} · หน่วย ${line.unit}`),
    "",
    factsBlock(facts),
    "",
    "บอกว่ารายการไหนคู่กับบรรทัดไหน พร้อมเหตุผลรายคู่ และรายการไหนที่ยังไม่มีคู่ที่ใช้ได้จริง"
  ].join("\n");
}
