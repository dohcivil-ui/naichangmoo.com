export const workPlanSchema = z.object({
  note: z.string(),
  activities: z.array(
    z.object({
      number: z.string(),
      title: z.string(),
      weightPpm: z.number().int(),
      startOffsetDays: z.number().int(),
      durationDays: z.number().int()
    })
  ),
  milestones: z.array(
    z.object({
      title: z.string(),
      activityNumbers: z.array(z.string())
    })
  )
});

export type WorkPlanDraft = z.infer<typeof workPlanSchema>;

