export type PromptInput = {
  projectName: string;
  contractBaht: string;
  durationDays: number;
  templateLabel: string;
  instruction?: string;
  current?: { number: string; title: string; weightPpm: string; startOffsetDays: number; durationDays: number }[];
  /**
   * บรรทัดข้อมูลที่ระบบคำนวณแล้ว ต่อท้ายเป็นบล็อกมาตรฐานเมื่อมีเท่านั้น
   *
   * ต่อท้ายเฉพาะเมื่อมี เพื่อให้โจทย์ที่ผู้เรียกเดิมส่ง เหมือนกับตอนที่วัดผลเทียบรุ่นทุกตัวอักษร
   */
  facts?: readonly string[];
};

export function buildWorkPlanTask(input: PromptInput): string {
  /*
   * มูลค่าสัญญาอยู่ในบล็อกข้อเท็จจริงเสมอ ไม่ใช่ในบรรทัดโจทย์
   *
   * ADR 0019 เขียนว่าเงินเข้า prompt ได้ทางเดียวคือบล็อกนี้ แต่ของจริงเคยวางมูลค่าสัญญาไว้
   * นอกบล็อก คำในเอกสารจึงแรงกว่าสิ่งที่โครงสร้างค้ำได้ ตอนนี้ค้ำได้จริงและมีเทสต์กันไว้ว่า
   * ตัดบล็อกออกแล้วต้องไม่เหลือจำนวนเงินอยู่ในโจทย์เลย
   */
  const tail = ["", factsBlock([`มูลค่าสัญญา ${input.contractBaht} บาท`, ...(input.facts ?? [])])];

  if (input.instruction) {
    return [
      `แผนปัจจุบันของโครงการ ${input.projectName}`,
      `ระยะเวลา ${input.durationDays} วัน`,
      "",
      "รายการงานปัจจุบัน (เลขลำดับ ชื่อ น้ำหนัก ppm วันเริ่ม ระยะเวลา)",
      ...(input.current ?? []).map(
        (activity) =>
          `${activity.number} | ${activity.title} | ${activity.weightPpm} | ${activity.startOffsetDays} | ${activity.durationDays}`
      ),
      "",
      `คำสั่งจากผู้ใช้: ${input.instruction}`,
      "",
      "แก้แผนตามคำสั่ง แล้วคืนแผนทั้งชุดกลับมาใหม่ทั้งหมด รวมรายการที่ไม่ได้แก้ด้วย",
      ...tail
    ].join("\n");
  }

  return [
    `ร่างแผนงานก่อสร้างสำหรับโครงการชื่อ ${input.projectName}`,
    `ประเภทงานที่ผู้ใช้เลือก ${input.templateLabel}`,
    `ระยะเวลา ${input.durationDays} วัน`,
    "",
    "อ่านชื่อโครงการให้ละเอียด ถ้าชื่อบอกจำนวนชั้นหรือจำนวนห้อง ให้แตกรายการงานตามนั้น",
    "จำนวนกิจกรรมที่เหมาะสมคือ 15 ถึง 30 รายการ และแบ่งงวดงาน 4 ถึง 10 งวด",
    ...tail
  ].join("\n");
}

/**
 * ผู้ช่วยตรวจแผน เปลี่ยน AI จาก "ร่างให้" เป็น "ที่ปรึกษาที่ทักก่อนพลาด"
 *
 * คู่แข่งไม่มี AI เลยแม้แต่จุดเดียว นี่คือช่องที่เรานำได้ในสัปดาห์เดียว
 *
 * หลักการเดียวกับผู้ช่วยร่าง: **ตัวเลขที่ผิดไม่ได้เราคิดเอง แบบจำลองแค่เรียบเรียง**
 * เงินทุนหมุนเวียนที่ต้องสำรอง สัดส่วนงวดที่หนักผิดปกติ ช่องว่างเงินเข้ากับเงินจ่าย
 * ทั้งหมดคำนวณฝั่งเราจาก BigInt แล้วส่งเป็นข้อความให้แบบจำลองจัดเรียงเป็นคำเตือนภาษาวิศวกร
 * ไม่ปล่อยให้มันคำนวณเงินเอง
 */
