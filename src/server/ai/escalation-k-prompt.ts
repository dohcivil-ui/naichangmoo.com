export type EscalationPreflightInput = {
  contractSignedOn: string | null;
  periodDeliveredOn: string | null;
  scopeSummary: string | null;
  providedIndexVariables: string[];
  hasPeriodAmount: boolean;
};

export function buildEscalationPreflightTask(input: EscalationPreflightInput, facts: string[]): string {
  return [
    "ตรวจความพร้อมของคำขอเงินชดเชยค่า K",
    "",
    "สิ่งที่ผู้ใช้กรอกมาแล้ว",
    `- วันลงนามสัญญา: ${input.contractSignedOn ?? "ยังไม่ได้กรอก"}`,
    `- วันส่งมอบงวดที่ขอ: ${input.periodDeliveredOn ?? "ยังไม่ได้กรอก"}`,
    `- ขอบเขตงานของงวด: ${input.scopeSummary ?? "ยังไม่ได้กรอก"}`,
    `- ตัวแปรดัชนีที่ให้ค่ามาแล้ว: ${input.providedIndexVariables.length > 0 ? input.providedIndexVariables.join(", ") : "ยังไม่มี"}`,
    `- มูลค่างานของงวด: ${input.hasPeriodAmount ? "กรอกแล้ว" : "ยังไม่ได้กรอก"}`,
    "",
    factsBlock(facts),
    "",
    "บอกว่ายังขาดอะไร และมีอะไรที่ขัดกันเองบ้าง ถ้าครบแล้วให้ตอบว่าพร้อม"
  ].join("\n");
}

export type EscalationExplainInput = {
  contractSignedOn: string | null;
  periodDeliveredOn: string | null;
  question: string;
};

export function buildEscalationExplainTask(input: EscalationExplainInput, facts: string[]): string {
  return [
    "อธิบายหลักเกณฑ์ค่า K ที่ใช้กับสัญญาฉบับนี้",
    "",
    `วันลงนามสัญญา: ${input.contractSignedOn ?? "ยังไม่ได้กรอก"}`,
    `วันส่งมอบงวดที่ขอ: ${input.periodDeliveredOn ?? "ยังไม่ได้กรอก"}`,
    "",
    factsBlock(facts),
    "",
    `คำถามของผู้ใช้: ${input.question}`,
    "",
    "อธิบายให้ผู้รับจ้างที่ไม่ใช่วิศวกรอ่านเข้าใจ และบอกด้วยว่าควรเปิดเอกสารตัวจริงตรวจข้อไหน"
  ].join("\n");
}

