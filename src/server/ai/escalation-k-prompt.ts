import { z } from "zod";
import { factsBlock } from "@/server/ai/facts-block";

/**
 * คำสั่งและ schema ของผู้ช่วยค่า K
 *
 * แยกจาก Next ด้วยเหตุผลเดียวกับ `work-plan-prompt.ts` คือสคริปต์เทียบรุ่นแบบจำลองต้องใช้
 * prompt ตัวเดียวกับที่แอปใช้จริง ไม่งั้นเราจะเลือกรุ่นจากหลักฐานที่วัดคนละอย่างกับงานจริง
 *
 * ผู้ช่วยตัวนี้ทำสองจังหวะที่ **แบบจำลองไม่คืนตัวเลขที่ไหลเข้าการคำนวณเลย**
 *
 *   `preflight` — บอกว่าอินพุตขาดอะไรก่อนจะไปคิดค่า K
 *   `explain`   — อธิบายว่าสัญญาฉบับนี้ตกอยู่ใต้หลักเกณฑ์ข้อไหน และทำไม
 *
 * เหตุที่เลือกสองจังหวะนี้ ไม่ใช่ `draft` ที่ให้เลือกสูตรจาก 35 สูตร: ชุดข้อมูล ว 109 ยัง
 * `reviewedBy: null` ทั้งห้าหมวด และ `computeK` ปฏิเสธทุกสูตรอยู่ในวันนี้ การให้แบบจำลอง
 * เลือกสูตรแล้วส่งต่อไปคำนวณเงินชดเชย เท่ากับเอาลายเซ็นผู้ใช้ไปค้ำตัวเลขที่ยังไม่มีใครค้ำ
 * เจ้าของงานอนุโลม `reviewedBy` **เฉพาะผู้ช่วยที่ไม่คืนตัวเลข** ส่วนตัวเงินยังปิดรอ IP-097
 *
 * **กับดักสองวัน** ที่ `explain` มีไว้เพื่อเรื่องนี้โดยเฉพาะ: มาตรการชั่วคราวปี 2569 ใช้เกณฑ์
 * ส่วนต่างที่ทริกด้วย *วันส่งมอบงวด* แต่กฎเดือนฐานทริกด้วย *วันลงนามสัญญา* สัญญาที่ลงนาม
 * ก่อนแต่ส่งมอบหลังจึงตกคนละกฎกันสองข้อพร้อมกัน การเลือกกฎเป็นโค้ด ผู้ช่วยแค่อธิบายให้เห็น
 */

export const escalationPreflightSchema = z.object({
  /** สิ่งที่ยังขาดก่อนจะคิดค่า K ได้ เรียงจากสำคัญไปน้อย */
  missing: z.array(
    z.object({
      item: z.string(),
      why: z.string()
    })
  ),
  /** สิ่งที่ให้มาแล้วแต่ดูขัดกันเอง เช่น วันส่งมอบมาก่อนวันลงนาม */
  conflicts: z.array(
    z.object({
      title: z.string(),
      detail: z.string()
    })
  ),
  /** พร้อมคิดค่า K หรือยัง เมื่อ false ต้องมีอย่างน้อยหนึ่งรายการใน missing หรือ conflicts */
  ready: z.boolean()
});

export type EscalationPreflight = z.infer<typeof escalationPreflightSchema>;

export const escalationExplainSchema = z.object({
  /** คำอธิบายหลัก ไม่เกินสี่ประโยค */
  summary: z.string(),
  /** ประเด็นที่ผู้ใช้ต้องรู้ทีละข้อ */
  points: z.array(
    z.object({
      title: z.string(),
      detail: z.string()
    })
  ),
  /** สิ่งที่ควรตรวจกับเอกสารตัวจริงก่อนใช้คำอธิบายนี้ */
  checkAgainstDocument: z.array(z.string())
});

export type EscalationExplain = z.infer<typeof escalationExplainSchema>;

