/** ปีคริสต์ศักราชของวันที่ ใช้หาว่าวันนั้นอยู่ในชุดข้อมูลปีไหน */
const gregorianYearOf = (date: string): number => Number.parseInt(date.slice(0, 4), 10);

export const buddhistYearOf = (date: string): number => gregorianYearOf(date) + 543;

/** ปีที่ชุดข้อมูลตั้งต้นครอบคลุม เรียงจากน้อยไปมาก */
export const coveredYears = (): number[] => DATASET.map((entry) => entry.buddhistYear);

export const holidayYear = (buddhistYear: number): HolidayYear | undefined =>
  DATASET.find((entry) => entry.buddhistYear === buddhistYear);

/** วันหยุดตั้งต้นทั้งหมดที่มีในชุดข้อมูล เรียงตามวันที่ */
export const defaultHolidays = (): ThaiHoliday[] =>
  DATASET.flatMap((entry) => entry.holidays).sort((a, b) => a.date.localeCompare(b.date));

/**
 * ปีที่ช่วงเวลาหนึ่งพาดผ่าน แต่ชุดข้อมูลยังไม่มี
 *
 * ผู้เรียกต้องเอาไปบอกผู้ใช้ ไม่ใช่เงียบแล้วนับทั้งปีเป็นวันทำงาน
 * เพราะแผนที่ไม่รู้ว่ามีวันหยุดจะสั้นกว่าความจริงเสมอ และผู้รับเหมาจะรู้ตัวตอนส่งงานไม่ทัน
 */
export function yearsWithoutData(fromDate: string, toDate: string): number[] {
  const first = buddhistYearOf(fromDate);
  const last = buddhistYearOf(toDate);
  if (!Number.isFinite(first) || !Number.isFinite(last) || last < first) return [];
  const covered = new Set(coveredYears());
  const missing: number[] = [];
  for (let year = first; year <= last; year += 1) if (!covered.has(year)) missing.push(year);
  return missing;
}

/** ปีที่ช่วงเวลาพาดผ่านและรายการยังไม่นิ่ง ต้องเตือนผู้ใช้ก่อนเอาไปผูกสัญญา */
export function provisionalYears(fromDate: string, toDate: string): HolidayYear[] {
  const first = buddhistYearOf(fromDate);
  const last = buddhistYearOf(toDate);
  return DATASET.filter(
    (entry) => entry.status === "provisional" && entry.buddhistYear >= first && entry.buddhistYear <= last
  );
}
