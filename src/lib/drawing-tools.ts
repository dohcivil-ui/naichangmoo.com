/**
 * เครื่องมือของหน้าทำงานวัดปริมาณ และด่านที่บอกว่าเครื่องมือไหนต้องมีสเกลก่อน (IP-227)
 *
 * ย้ายชนิดเครื่องมือออกมาจาก component เพื่อให้ด่านสเกลถูกเทสต์ได้โดยไม่ต้องมีจอ
 * ด่านนี้ตัดสินว่าผู้ใช้กดปุ่มไหนได้บ้างในหน้าที่ยังไม่ได้ตั้งสเกล ซึ่งเป็นเรื่องที่ผิดแล้ว
 * คนทำงานไม่ได้ทั้งหน้า จึงควรอยู่ในที่ที่เทสต์เฝ้าได้ ไม่ใช่ในเงื่อนไขกลาง component
 */

import type { MeasurementKind } from "@/lib/drawing-measurement";

/**
 * เครื่องมือทั้งหมดสิบตัว
 *
 * `gridline` กับ `dimension` เป็นของใหม่ในก้อนนี้ ตามลำดับงานที่เจ้าของงานใช้จริง
 * คือร่างแนวเสาก่อน ใส่ระยะที่แบบเขียน แล้วสเกลตามมาเอง
 *
 * **เคยมี `pan` เป็นเครื่องมือที่สิบเอ็ด ถอดออกเมื่อ 2026-09-05** เพราะมันคือ `select`
 * ที่ถอดความสามารถออกไปหนึ่งอย่าง ไล่โค้ดแล้วต่างกันจุดเดียวคือคลิกแล้วปล่อยโดยไม่ขยับ
 * `select` เลือกของที่วัดไว้ ส่วน `pan` ไม่ทำอะไร · การลากเลื่อนแบบและดับเบิลคลิกซูม
 * เหมือนกันเป๊ะทั้งสองตัว และปุ่มกลางเมาส์เลื่อนแบบได้อยู่แล้วไม่ว่าถืออะไรอยู่
 * เจ้าของงานสังเกตเห็นเองจากหน้าจอแล้วสั่งเอาออก
 */
export type Tool =
  | "select"
  | "erase"
  | "scale"
  | "room"
  | "gridline"
  | "dimension"
  | MeasurementKind;

/**
 * เครื่องมือนี้ต้องมีสเกลของหน้าก่อนถึงจะใช้ได้หรือไม่
 *
 * **เกณฑ์เดียวคือเครื่องมือนั้นคืนค่าเป็นเมตรหรือตารางเมตรหรือเปล่า** ถ้าใช่ก็ต้องมีสเกล
 * เพราะไม่มีเลขให้คูณ ถ้าไม่ใช่ก็ไม่ต้อง เพราะจำนวนกับพิกัดไม่ต้องแปลงหน่วย
 *
 * โค้ดเดิมล็อกเครื่องมือห้าตัวรวดจนกว่าจะตั้งสเกล ซึ่งกว้างเกินเกณฑ์นี้และไปขวางลำดับงาน
 * ที่ต้องร่างกริดก่อน · ภาพหน้าจอแอปเดิมของเจ้าของงาน (2026-09-02) เป็นหลักฐานว่าเส้นกริด
 * ระยะจริง และหมุดนับจำนวน ถูกวางครบทั้งที่แถบสถานะยังขึ้นว่า "สเกล: ยังไม่ตั้ง"
 *
 * เทสต์บังคับตารางนี้ทีละช่องครบสิบเอ็ดค่า วันที่มีคนเผลอขยายด่านกลับไปกว้างเหมือนเดิม
 * เทสต์ต้องแดงทันที ไม่ใช่รอเจ้าของงานกดเจอเอง
 */
export function toolNeedsScale(tool: Tool): boolean {
  switch (tool) {
    case "length":
    case "polyline":
    case "rect":
    case "area":
    case "room":
      return true;
    case "select":
    /* ลบไม่ต้องมีสเกล เพราะมันไม่ได้ตอบเป็นเมตร มันแค่เอาของที่วาดไว้ออก
       และของที่ต้องลบมากที่สุดคือแนวเสากับระยะที่แบบเขียน ซึ่งวาดได้ตั้งแต่ยังไม่ตั้งสเกล */
    case "erase":
    case "scale":
    case "count":
    case "gridline":
    case "dimension":
      return false;
  }
}
