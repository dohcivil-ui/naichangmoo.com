import { describe, expect, it } from "vitest";
import { isPromoLive, promoEndsAt, promoOffers } from "./landing-v3-data";

/**
 * นาฬิกานับถอยหลังของบล็อกโปรโมชั่นเคยเขียนไว้เป็น "อีกห้าวันจากตอนนี้" ซึ่งรีเซ็ตทุกครั้ง
 * ที่มีคนโหลดหน้า จึงเหลือห้าวันตลอดกาลและไม่มีวันหมด · โปรโมชั่นที่ไม่มีวันจบแต่แสดงว่า
 * กำลังจะจบ เป็นคำแถลงเท็จเรื่องเวลา ตระกูลเดียวกับเปอร์เซ็นต์ความคืบหน้าที่ ADR 0015 ปฏิเสธ
 *
 * ด่านชุดนี้พิสูจน์ว่าวันหมดอายุมีอยู่จริงและมีผลจริง โดยไม่ต้องรอถึงวันนั้น
 */
describe("วันหมดอายุของโปรโมชั่น", () => {
  const ends = new Date(promoEndsAt);

  it("ยังไม่หมดอายุก่อนถึงวันสิ้นสุด", () => {
    expect(isPromoLive(new Date(ends.getTime() - 1000))).toBe(true);
  });

  it("หมดอายุเมื่อถึงวินาทีที่ระบุ", () => {
    expect(isPromoLive(ends)).toBe(false);
  });

  it("หมดอายุแล้วไม่กลับมามีชีวิตอีก ไม่ว่าเวลาผ่านไปนานแค่ไหน", () => {
    /* ข้อนี้คือสิ่งที่สูตรเดิมทำผิด — มันคำนวณจากเวลาปัจจุบันทุกครั้ง จึงไม่เคยถึงศูนย์ */
    const aYearLater = new Date(ends.getTime() + 365 * 24 * 60 * 60 * 1000);
    expect(isPromoLive(aYearLater)).toBe(false);
  });

  it("วันสิ้นสุดเป็นเวลาที่อ่านได้จริง ไม่ใช่สตริงที่พิมพ์ผิด", () => {
    expect(Number.isNaN(ends.getTime())).toBe(false);
  });
});

/**
 * ราคาในไฟล์นี้เป็นค่าสมมติที่รอเจ้าของงานยืนยัน สิ่งที่กันไม่ให้มันถูกอ่านเป็นราคาจริง
 * คือหมายเหตุบนหัวบล็อก · ส่วนถ้อยคำปุ่มเป็นคำแถลงตาม ADR 0015 จึงต้องมาจากทะเบียน
 * ไม่ใช่จากไฟล์นี้ — ด่านนี้กันไม่ให้มีใครเติมฟิลด์ถ้อยคำปุ่มกลับเข้ามา
 */
describe("การ์ดโปรโมชั่น", () => {
  it("ไม่มีถ้อยคำปุ่มพิมพ์ตายอยู่ในข้อมูลราคา", () => {
    for (const offer of promoOffers) {
      expect(Object.keys(offer)).not.toContain("ctaLabel");
    }
  });

  it("ทุกใบมี slug ให้ไปถามทะเบียน", () => {
    for (const offer of promoOffers) {
      expect(offer.slug.length).toBeGreaterThan(0);
    }
  });
});
