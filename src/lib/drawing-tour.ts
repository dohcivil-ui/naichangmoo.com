/** ปุ่มที่ขั้นนี้ชี้ไป — ชื่อตรงกับ `data-tour-target` ที่ปุ่มจริงบนแถบเครื่องมือติดไว้ */
export type TourTarget = "open" | "scale";

export type TourStep = {
  /** ลำดับของขั้นนี้ เริ่มที่ 1 เพื่อให้เอาไปแสดงตรง ๆ ได้ */
  index: number;
  /** จำนวนขั้นทั้งหมด — คงที่ ไม่หดตามขั้นที่ผ่านไปแล้ว คนจึงรู้ว่าเหลืออีกกี่ขั้น */
  total: number;
  target: TourTarget;
  title: string;
  /** ทำไมเครื่องมือถึงกดไม่ได้ตอนนี้ — เขียนเป็นเหตุผล ไม่ใช่คำสั่ง */
  reason: string;
  /** ต้องทำอะไรต่อ */
  action: string;
  /** คำบนปุ่มที่พาไปทำสิ่งนั้นทันที */
  actionLabel: string;
  /** ทางอื่นที่ได้ผลเหมือนกัน ไม่มีก็เป็น null */
  alternative: string | null;
};

/** ขั้นทั้งหมดของทัวร์ เรียงตามลำดับที่ต้องทำจริง */
