/**
 * ขั้นที่ควรพาทำตอนนี้ — คืน `null` เมื่อไม่มีอะไรขวางอยู่แล้ว
 *
 * ลำดับการตัดสินคือ **ไม่มีแบบมาก่อนเสมอ** แม้สถานะจะบอกว่ามีสเกลค้างอยู่ก็ตาม
 * (เกิดได้ตอนที่หน้าเพิ่งกู้สถานะเก่ากลับมาแต่ไฟล์ยังไม่ถูกเปิด) เพราะสเกลของหน้าที่ไม่มีแบบ
 * ให้ดูนั้นใช้ทำอะไรไม่ได้เลย และพาคนไปกดเครื่องมือที่ยังดับอยู่คือการโกหก
 */
export function drawingTourStep(state: { hasDrawing: boolean; hasPageScale: boolean }): TourStep | null {
  if (!state.hasDrawing) return STEPS[0];
  if (!state.hasPageScale) return STEPS[1];
  return null;
}
