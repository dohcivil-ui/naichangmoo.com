export function isQuantityMethod(value: string): value is QuantityMethod {
  return QUANTITY_METHODS.some((kind) => kind.key === value);
}

export function quantityMethodKind(method: QuantityMethod): QuantityMethodKind {
  const found = QUANTITY_METHODS.find((kind) => kind.key === method);
  // ทะเบียนครบทุกค่าของ union อยู่แล้ว และเทสต์เฝ้าไว้ บรรทัดนี้จึงเป็นด่านสุดท้ายเฉย ๆ
  if (!found) throw new Error(`ไม่รู้จักวิธีที่มาของปริมาณ: ${method}`);
  return found;
}

/**
 * วิธีนี้ต้องผูกกับข้อเสนอของผู้ช่วยหรือไม่ — ต้องให้คำตอบเดียวกับ CHECK ในฐานข้อมูล
 *
 * มีเทสต์เดินทะเบียนเทียบกับชื่อ CHECK ที่ migration สร้างไว้ ถ้าวันหนึ่งมีคนเพิ่มวิธีใหม่
 * ที่โมเดลเป็นคนเสนอแต่ลืมแก้ CHECK เทสต์ต้องแดง ไม่ใช่ปล่อยให้ค่าที่ไม่มีที่มาไหลเข้าฐาน
 */
export function methodRequiresProposal(method: QuantityMethod): boolean {
  return quantityMethodKind(method).requiresProposal;
}

/**
 * ข้อเท็จจริงประกอบที่เก็บลงคอลัมน์ jsonb คู่กับวิธี
 *
 * `version` ตายตัวเพราะ jsonb ไม่มี migration ให้ วันที่รูปทรงนี้ต้องเปลี่ยนจริง ให้เพิ่ม
 * เลขรุ่นใหม่แล้วอ่านทั้งสองรุ่นได้ ไม่ใช่แก้ความหมายของรุ่นเดิมจนข้อมูลเก่าอ่านผิด
 *
 * **ทุกช่องเป็นของที่วัดได้ ไม่มีช่องไหนเป็นความเห็น** ไม่มีระดับความเชื่อถือ ไม่มีคะแนน
 * ไม่มีธงว่าน่าสงสัย — ของพวกนั้นคำนวณจากข้อเท็จจริงเหล่านี้เมื่อถูกถาม
 */
export type MethodContext = {
  version: 1;
  /** อุปกรณ์ที่ใช้ชี้จุด เก็บเพราะปากกากับนิ้วให้ความเที่ยงไม่เท่ากัน ไม่ได้แปลว่าอันไหนดีกว่า */
  pointerType?: "mouse" | "pen" | "touch";
  /** แถวสเกลที่ใช้แปลงหน่วยตอนนั้น ทำให้ย้อนได้ว่าคูณด้วยอะไร */
  calibrationId?: string;
};

const POINTER_TYPES = new Set(["mouse", "pen", "touch"]);

/**
 * อ่านค่าที่ออกมาจาก jsonb ให้เป็นรูปทรงที่เชื่อได้
 *
 * ทุกอย่างที่ออกจาก jsonb คือ `unknown` เสมอ ฐานข้อมูลไม่ได้รับประกันรูปทรงให้เลย
 * คืน `null` เมื่ออ่านไม่ได้ ซึ่งเป็นคำตอบที่ถูก ไม่ใช่ความล้มเหลว เพราะคอลัมน์นี้ว่างได้
 */
export function parseMethodContext(value: unknown): MethodContext | null {
  if (typeof value !== "object" || value === null) return null;
  const raw = value as Record<string, unknown>;
  if (raw.version !== 1) return null;

  const context: MethodContext = { version: 1 };

  if (typeof raw.pointerType === "string") {
    if (!POINTER_TYPES.has(raw.pointerType)) return null;
    context.pointerType = raw.pointerType as MethodContext["pointerType"];
  }
  if (typeof raw.calibrationId === "string") {
    if (raw.calibrationId.length === 0) return null;
    context.calibrationId = raw.calibrationId;
  }

  return context;
}

/**
 * ต้องกำกับที่มาให้เห็นในตารางและในเอกสารที่พิมพ์ออกไปหรือไม่
 *
 * **นี่คือฟังก์ชันคำพิพากษาเพียงตัวเดียวของทั้งเรื่องนี้ และเป็นที่เดียวที่ต้องแก้
 * วันที่ปัญญาประดิษฐ์เก่งพอ** โครงสร้างข้อมูลไม่ต้องขยับสักคอลัมน์ ข้อมูลเก่าไม่ต้องย้าย
 * และแถวที่บันทึกไว้เมื่อวานยังตอบคำถามใหม่ได้ เพราะมันเก็บข้อเท็จจริงไว้ ไม่ได้เก็บคำตัดสิน
 *
 * เกณฑ์วันนี้: **ค่าที่โมเดลเป็นคนเสนอต้องกำกับ ค่าที่คนเป็นคนตัดสินทุกวิธีไม่ต้อง**
 * `region_trace` อยู่ฝั่งไม่ต้องกำกับ เพราะโค้ดเป็นแค่คนเสนอรูป ส่วนคนเป็นผู้ดูรูปที่ทับ
 * บนแบบแล้วกดยืนยัน ซึ่งเป็นการตัดสินด้วยตาคนเหมือนการชี้จุดเอง
 */
export function methodNeedsDisclosure(method: QuantityMethod): boolean {
  return quantityMethodKind(method).requiresProposal;
}
