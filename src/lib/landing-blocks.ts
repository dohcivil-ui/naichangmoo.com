/** หาบล็อกจากชื่อในโค้ด — คืน undefined ถ้าไม่มี ผู้เรียกต้องเช็กเอง */
export function findLandingBlock(key: string): LandingBlock | undefined {
  return landingBlocks.find((block) => block.key === key);
}

/** บล็อกที่ผู้ดูแลปิดได้ ใช้ตอนสร้างหน้า admin ในก้อนถัดไป */
export function closableLandingBlocks(): readonly LandingBlock[] {
  return landingBlocks.filter((block) => block.lockedReason === null);
}
